export function labelPattern(key: string): string {
  return key.replace(/\.\d+(?=\.|$)/g, ".#");
}

// Interface keys are the English text itself, so the text is its own name.
function uiLabel(key: string): string {
  const text = key.replace(/^\*/, "").replace(/\s+/g, " ").trim();
  const plain = text === text.toUpperCase() && /[A-Z]/.test(text) ? text.charAt(0) + text.slice(1).toLowerCase() : text;
  return plain.length > 60 ? `${plain.slice(0, 57).trimEnd()}...` : plain;
}

export function copyLabel(catalog: CatalogId, key: string): string | null {
  if (catalog === "ui") return uiLabel(key);
  const template = KEY_LABELS[catalog][labelPattern(key)];
  if (!template) return null;
  const positions = [...key.matchAll(/\.(\d+)(?=\.|$)/g)].map((match) => Number(match[1]) + 1);
  return template.replace("{n}", String(positions[0] ?? "")).replace("{m}", String(positions[1] ?? ""));
}

export function sectionLabel(section: string): string {
  return SECTION_LABELS[section] ?? section;
}
